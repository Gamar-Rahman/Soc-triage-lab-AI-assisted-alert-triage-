/* Zero-dependency, auditable offline triage helpers. NOT a predictive ML model. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  root.SOC_CORE = api;
})(typeof window !== 'undefined' ? window : globalThis, function () {
  'use strict';
  const actions = ['escalate', 'investigate', 'close'];
  function scoreCase(c) {
    const weights = (c.signals || []).reduce((sum, f) => sum + (Number.isFinite(f.weight) ? Math.max(0, f.weight) : 0), 0);
    return Math.min(100, Math.round(10 + weights));
  }
  function level(score) { return score >= 75 ? 'High' : score >= 45 ? 'Medium' : 'Low'; }
  function coverageCase(c) {
    const coverage = c.coverage || [];
    const count = coverage.filter(x => x.status === 'available').length;
    return { count, total: coverage.length, percent: coverage.length ? Math.round(100 * count / coverage.length) : 0,
      gaps: coverage.filter(x => x.status !== 'available').map(x => x.name) };
  }
  function validateCase(c) {
    if (!c || !/^[A-Za-z0-9_-]{2,40}$/.test(String(c.id || ''))) return false;
    if (!Array.isArray(c.events) || !Array.isArray(c.signals) || !Array.isArray(c.coverage)) return false;
    const ids = new Set(c.events.map(e => e.id));
    return c.signals.every(s => Array.isArray(s.source_ids) && s.source_ids.length && s.source_ids.every(id => ids.has(id)) && ['observed', 'inference'].includes(s.type));
  }
  function sourceIntegrity(c) {
    const ids = new Set((c.events || []).map(e => e.id));
    const claims = c.signals || [];
    return { backed: claims.filter(s => s.source_ids && s.source_ids.length && s.source_ids.every(id => ids.has(id))).length,
      total: claims.length };
  }
  function canDecide(c, action, note, gapAcknowledged, verifiedIds) {
    if (!actions.includes(action)) return { allowed: false, reason: 'Choose a valid disposition.' };
    if (typeof note !== 'string' || note.trim().length < 15) return { allowed: false, reason: 'Add at least 15 characters explaining your decision.' };
    if (coverageCase(c).gaps.length && action !== 'investigate' && !gapAcknowledged)
      return { allowed: false, reason: 'Acknowledge the missing evidence before final disposition.' };
    if (action === 'close' && level(scoreCase(c)) === 'High' && verifiedIds.length < 2)
      return { allowed: false, reason: 'Closing a high-risk case requires review of at least two source records.' };
    return { allowed: true, reason: '' };
  }
  function buildHandoff(c, decision, note, verifiedIds) {
    const s = scoreCase(c), cov = coverageCase(c);
    const findings = c.signals.map(f => `- ${f.type === 'observed' ? 'OBSERVED' : 'INFERENCE'}: ${f.label} [${f.source_ids.join(', ')}]`).join('\n');
    const gaps = cov.gaps.length ? cov.gaps.map(x => '- ' + x).join('\n') : '- None documented';
    return `# ${c.id} — ${c.title}\n\n**Disposition:** ${decision || 'Pending analyst review'}\n**Rule-based demonstration score:** ${s}/100 (${level(s)})\n**Evidence completeness:** ${cov.count}/${cov.total} sources\n**Actor:** ${c.user}\n**Asset:** ${c.asset}\n**Timestamp:** ${c.timestamp}\n\n## Incident summary\n${c.summary}\n\n## Supported risk factors\n${findings}\n\n## Evidence gaps\n${gaps}\n\n## Verified raw source records\n${(verifiedIds || []).length ? verifiedIds.map(x => '- ' + x).join('\n') : '- None checked yet'}\n\n## Suggested next investigation steps\n${c.next_steps.map(x => '- ' + x).join('\n')}\n\n## Analyst rationale (editable)\n${note || '[Analyst must add reasoning]'}\n\n---\nGenerated by a synthetic-data training prototype; no remediation performed.\n`;
  }
  return { scoreCase, level, coverageCase, validateCase, sourceIntegrity, canDecide, buildHandoff };
});
